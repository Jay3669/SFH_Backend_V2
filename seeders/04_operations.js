import crypto from 'node:crypto';
import MenuItem from '../src/models/menuItem.model.js';
import StockItem from '../src/models/stockItem.model.js';
import User from '../src/models/user.model.js';
import Recipe from '../src/models/recipes.model.js';
import RecipeVersion from '../src/models/recipeVersion.model.js';
import { StockMovement } from '../src/models/stock.model.js';
import ProductionRecord from '../src/models/productionRecord.model.js';
import ProductionIngredient from '../src/models/productionIngredient.model.js';
import ProductionCostDetail from '../src/models/productionCostDetail.model.js';
import ProductionCancellation from '../src/models/productionCancellation.model.js';
import ProductionRecovery from '../src/models/productionRecovery.model.js';
import ProductionDay from '../src/models/productionDay.model.js';
import ProductionDayItem from '../src/models/productionDayItem.model.js';
import ProductionSale from '../src/models/productionSale.model.js';
import ProductionSaleItem from '../src/models/productionSaleItem.model.js';
import OperatingExpense from '../src/models/operatingExpense.model.js';
import CashDrawer from '../src/models/cashDrawer.model.js';

const round2 = (value) => Math.round((value + Number.EPSILON) * 100) / 100;
const dateForIndex = (i) => {
    const date = new Date();
    date.setUTCDate(date.getUTCDate() - (90 + i * 2));
    return date.toISOString().slice(0, 10);
};

export async function seedOperations(transaction) {
    const menuItems = await MenuItem.findAll({ limit:50, order:[['name','ASC']], transaction });
    const stockItems = await StockItem.findAll({ limit:50, order:[['name','ASC']], transaction });
    const creator = await User.findOne({ where:{ role:'manager' }, transaction }) || await User.findOne({ transaction });
    const cashier = await User.findOne({ where:{ role:'cashier' }, transaction }) || creator;
    let productionCreated=0, ingredientsCreated=0, costDetailsCreated=0, saleCreated=0, saleItemsCreated=0;
    let daysCreated=0, dayItemsCreated=0, expensesCreated=0, drawersCreated=0, cancellationsCreated=0, recoveriesCreated=0;

    for (let i=0;i<50;i+=1) {
        const menu = menuItems[i];
        const stock = stockItems[i%stockItems.length];
        if (!menu || !stock) continue;
        const recipe = await Recipe.findOne({ where:{ menuItemId:menu.id }, transaction });
        const version = recipe ? await RecipeVersion.findOne({ where:{ recipeId:recipe.id,version:1 }, transaction }) : null;
        if (!recipe || !version) continue;

        const productionDate = dateForIndex(i);
        const plates = 20 + (i % 12);
        const quantity = 5 + (i % 5);
        const ingredientCost = round2(quantity * Number(stock.unitCost));
        const additionalCost = round2(80 + (i % 7) * 25);
        const totalCost = round2(ingredientCost + additionalCost);
        const costPerPlate = round2(totalCost / plates);
        const reference = `PRD-QA-${String(i+1).padStart(3,'0')}`;
        const [record,created] = await ProductionRecord.findOrCreate({
            where:{ reference },
            defaults:{
                reference,idempotencyKey:`idem-${crypto.createHash('sha256').update(reference).digest('hex').slice(0,60)}`,
                requestHash:crypto.createHash('sha256').update(`${reference}:${productionDate}`).digest('hex'),
                menuItemId:menu.id,recipeVersionId:version.id,productionDate,productionQuantity:quantity,
                productionUnit:'kg',expectedPlateCount:plates,actualPlateCount:plates,
                sellingPricePerPlate:Number(menu.price),totalIngredientCost:ingredientCost,additionalCost,
                totalProductionCost:totalCost,costPerKg:round2(totalCost/quantity),costPerPlate,
                notes:'Realistic quality-tested production batch generated by the non-production seeder.',
                preparedBy:creator.id,status:'confirmed',
            }, transaction,
        });
        if (created) productionCreated+=1;

        const existingMovement = await StockMovement.findOne({ where:{ referenceType:'qa-production', referenceId:record.id }, transaction });
        let movement;
        if (existingMovement) movement = existingMovement;
        else {
            const before = Number(stock.quantity);
            movement = await StockMovement.create({
                stockItemId:stock.id,type:'out',quantity:quantity,unitCost:Number(stock.unitCost),
                change:-quantity,beforeQuantity:before,afterQuantity:Math.max(0,before-quantity),unit:'kg',
                reason:`QA production batch ${reference}`,referenceType:'qa-production',referenceId:record.id,actorUserId:creator.id,
            }, { transaction });
            await stock.update({ quantity:Math.max(0,before-quantity) }, { transaction });
        }

        const [productionIngredient,ingredientCreated] = await ProductionIngredient.findOrCreate({
            where:{ productionRecordId:record.id,stockItemId:stock.id },
            defaults:{
                productionRecordId:record.id,stockItemId:stock.id,ingredientName:stock.name,
                theoreticalQuantity:quantity,quantityDeducted:quantity,unit:'kg',wastagePercentage:3,
                recipeWastagePercentage:3,unitCost:Number(stock.unitCost),totalCost:ingredientCost,
                balanceAfter:Number(movement.afterQuantity),stockMovementId:movement.id,
            }, transaction,
        });
        if (ingredientCreated) ingredientsCreated+=1;

        for (const [name,amount] of [['Cooking fuel',round2(additionalCost*0.5)],['Labour and packaging',round2(additionalCost*0.5)]]) {
            const [costRow,costCreated] = await ProductionCostDetail.findOrCreate({
                where:{ productionRecordId:record.id,name },
                defaults:{ productionRecordId:record.id,name,amount }, transaction,
            });
            if (costCreated) costDetailsCreated+=1;
        }

        const [day,dayCreated] = await ProductionDay.findOrCreate({
            where:{ productionDate },
            defaults:{ productionDate,isClosed:true,closedAt:new Date(`${productionDate}T18:00:00+05:30`),closedBy:creator.id,
                totalProducedPlates:plates,totalSoldPlates:plates-(i%4),totalWastagePlates:i%4,
                totalProductionCost:totalCost,totalSalesRevenue:round2((plates-(i%4))*Number(menu.price)),
                totalWastageCost:round2((i%4)*costPerPlate) },
            transaction,
        });
        if (dayCreated) daysCreated+=1;
        const [dayItem,dayItemCreated] = await ProductionDayItem.findOrCreate({
            where:{ productionDate,menuItemId:menu.id },
            defaults:{ productionDate,menuItemId:menu.id,menuItemName:menu.name,producedPlates:plates,
                soldPlates:plates-(i%4),wastagePlates:i%4,productionCost:totalCost,
                salesRevenue:round2((plates-(i%4))*Number(menu.price)),wastageCost:round2((i%4)*costPerPlate) },
            transaction,
        });
        if (dayItemCreated) dayItemsCreated+=1;

        const saleReference=`POS-QA-${String(i+1).padStart(4,'0')}`;
        const sold=plates-(i%4);
        const subtotal=round2(sold*Number(menu.price));
        const discountAmount=i%5===0?round2(subtotal*0.05):0;
        const taxable=round2(subtotal-discountAmount);
        const taxAmount=round2(taxable*0.05);
        const total=round2(taxable+taxAmount);
        const methods=['cash','upi','card','split'];
        const method=methods[i%methods.length];
        const [sale,saleCreatedRow] = await ProductionSale.findOrCreate({
            where:{ reference:saleReference },
            defaults:{
                reference:saleReference,idempotencyKey:`sale-${crypto.createHash('sha256').update(saleReference).digest('hex').slice(0,60)}`,
                requestHash:crypto.createHash('sha256').update(`${saleReference}:${subtotal}:${total}`).digest('hex'),
                productionDate,subtotal,discountAmount,taxRate:5,taxAmount,packingCharge:0,
                additionalCharges:[],totalAmount:total,paymentMethod:method,
                paymentBreakdown:method==='split'?{cash:round2(total/2),upi:round2(total-total/2)}:{[method]:total},
                paymentStatus:'completed',cashierId:cashier.id,
            }, transaction,
        });
        if (saleCreatedRow) saleCreated+=1;
        const [saleItem,itemCreated] = await ProductionSaleItem.findOrCreate({
            where:{ saleId:sale.id,productionRecordId:record.id },
            defaults:{ saleId:sale.id,productionRecordId:record.id,menuItemId:menu.id,menuItemName:menu.name,
                quantity:sold,unitPrice:Number(menu.price),costPerPlate,discountAmount,
                totalPrice:taxable },
            transaction,
        });
        if (itemCreated) saleItemsCreated+=1;

        if (i<10) {
            const [cancellation,cancelCreated] = await ProductionCancellation.findOrCreate({
                where:{ productionRecordId:record.id },
                defaults:{ productionRecordId:record.id,reason:'Batch quality check variance',
                    notes:'Cancelled in the QA fixture for realistic recovery testing.',cancelledBy:creator.id,cancelledAt:new Date(`${productionDate}T12:30:00+05:30`) },
                transaction,
            });
            if (cancelCreated) cancellationsCreated+=1;
            const [recovery,recoveryCreated] = await ProductionRecovery.findOrCreate({
                where:{ cancellationId:cancellation.id,productionIngredientId:productionIngredient.id },
                defaults:{ cancellationId:cancellation.id,productionIngredientId:productionIngredient.id,
                    quantityRecovered:0.25,unit:'kg',stockMovementId:movement.id }, transaction,
            });
            if (recoveryCreated) recoveriesCreated+=1;
        }
    }

    for (let i=0;i<50;i+=1) {
        const date=dateForIndex(i);
        const [drawer,drawerCreated] = await CashDrawer.findOrCreate({
            where:{ business_date:date,cashier_id:cashier.id },
            defaults:{ business_date:date,cashier_id:cashier.id,opening_balance:5000+i*50,
                actual_cash:5200+i*50,expected_cash:5200+i*50,variance:0,cash_taken:100,status:'closed',
                opened_at:new Date(`${date}T09:00:00+05:30`),closed_at:new Date(`${date}T22:00:00+05:30`) },
            transaction,
        });
        if (drawerCreated) drawersCreated+=1;
        const [expense,expenseCreated] = await OperatingExpense.findOrCreate({
            where:{ expenseDate:date,description:`QA fixture operating expense ${i+1}` },
            defaults:{ expenseDate:date,category:['Utilities','Ingredients','Packaging','Transport','Maintenance'][i%5],
                description:`QA fixture operating expense ${i+1}`,amount:1200+(i%12)*250,createdBy:creator.id },
            transaction,
        });
        if (expenseCreated) expensesCreated+=1;
    }

    return { productionRecordsCreated:productionCreated,productionIngredientsCreated:ingredientsCreated,
        productionCostDetailsCreated:costDetailsCreated,productionDaysCreated:daysCreated,
        productionDayItemsCreated:dayItemsCreated,productionSalesCreated:saleCreated,
        productionSaleItemsCreated:saleItemsCreated,cashDrawersCreated:drawersCreated,
        operatingExpensesCreated:expensesCreated,cancellationsCreated,recoveriesCreated };
}
